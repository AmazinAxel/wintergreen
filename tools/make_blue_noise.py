#!/usr/bin/env python3
"""Generate the 64x64 blue-noise threshold map (void-and-cluster, Ulichney 1993).

Writes wintergreen/content/BlueNoise.h: the rank of every cell, 0..4095, scaled
to 0..255. The converter (images, covers, sleep cover) and
tools/make_sleep_image.py (the wordmark, which parses the header) dither with
it, so the device never dithers anything. Deterministic: same seed, same table.

  nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (ps: [ps.numpy])' \
    -c python3 tools/make_blue_noise.py
"""

import os

import numpy as np

N = 64
SIGMA = 1.5


def energy_kernel():
    r = np.arange(N)
    d = np.minimum(r, N - r).astype(float)
    g = np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA**2))
    return np.fft.rfft2(g)


K = energy_kernel()


def energy(bits):
    return np.fft.irfft2(np.fft.rfft2(bits) * K, s=bits.shape)


def tightest_cluster(bits):
    e = energy(bits)
    e[bits == 0] = -np.inf
    return np.unravel_index(np.argmax(e), e.shape)


def largest_void(bits):
    e = energy(bits)
    e[bits == 1] = np.inf
    return np.unravel_index(np.argmin(e), e.shape)


def main():
    rng = np.random.default_rng(12345)
    ones = N * N // 10
    bits = np.zeros((N, N))
    bits.flat[rng.choice(N * N, ones, replace=False)] = 1
    # Initial binary pattern: move ones from clusters to voids until stable.
    while True:
        c = tightest_cluster(bits)
        bits[c] = 0
        v = largest_void(bits)
        if v == c:
            bits[c] = 1
            break
        bits[v] = 1
    rank = np.zeros((N, N), dtype=int)
    proto = bits.copy()
    # Phase 1: ranks below the initial pattern.
    b = proto.copy()
    for r in range(ones - 1, -1, -1):
        c = tightest_cluster(b)
        b[c] = 0
        rank[c] = r
    # Phases 2 and 3: fill voids.
    b = proto.copy()
    for r in range(ones, N * N):
        v = largest_void(b)
        b[v] = 1
        rank[v] = r
    table = (rank * 256 // (N * N)).astype(np.uint8)
    out = os.path.join(os.path.dirname(__file__), "..", "wintergreen", "content", "BlueNoise.h")
    lines = [
        "#pragma once",
        "",
        "// 64x64 blue-noise threshold map (void-and-cluster), generated by",
        "// tools/make_blue_noise.py; tools/make_sleep_image.py parses it. Host only:",
        "// the converter dithers, the device never does.",
        "",
        "#include <cstdint>",
        "",
        "namespace wintergreen {",
        "",
        "inline constexpr int kBlueNoiseSize = 64;",
        "inline constexpr uint8_t kBlueNoise[64 * 64] = {",
    ]
    flat = table.flatten()
    for i in range(0, N * N, 16):
        lines.append("    " + ", ".join("%3d" % v for v in flat[i : i + 16]) + ",")
    lines += ["};", "", "}  // namespace wintergreen", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
